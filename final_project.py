"""Solving analytical equations for T_w and T_b."""

# Define the equations
def equations(vars):
    T_w, T_b = vars
    eq1 = (2*T_opt - T_w)**4 - T_w**4 - q * (alpha_w - alpha_b)
    eq2 = T_b**4 - (2*T_opt - T_b)**4 - q * (alpha_w - alpha_b)
    return [eq1, eq2]

# Initial guesses for T_w and T_b based on graphs
initial_guess = [290, 300]

# Solve the system of equations
T_w, T_b = fsolve(equations, initial_guess) - 273.15

